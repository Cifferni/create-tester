// tester 配置文件(白话版说明)
// ═══════════════════════════════════════════════════════════════════
// 这个文件是 tester 的"总开关面板",管两件事:
//   1) 被测系统有哪些环境(测试/预发/生产各是什么地址)
//   2) 内置功能开还是关(选择器缓存、跨用例变量、失败重试、视觉兜底)
//
// 怎么看/怎么改:
//   - 正常测试人员不用碰这个文件——地址、账号在对话里说,AI 会帮你改。
//   - 你要改的是"默认值":改完保存,下次跑测试就生效。
//   - 紧急临时切换(比如这次先关掉缓存):不用改文件,直接设环境变量即可,
//     环境变量的优先级永远比这里的值高(env > 本文件 > 内置默认)。
//
// 每一行后面都有"这句话是干嘛的",照着改就行。
// ═══════════════════════════════════════════════════════════════════

export const testerConfig = {
  // ── 被测系统的环境地址表 ────────────────────────────────────────
  // 干嘛用的:你有多套被测环境(测试环境/预发环境/生产环境),把每套的
  //   地址都记在这里。跑的时候用 `tester run --env 名字` 或 `TESTER_ENV=名字`
  //   就能一键切到那套环境,不用每次手改地址。
  // 怎么改:把 "名字: '地址'" 替换成你的。名字随便起,别重样就行。
  // 注意:如果同时设了 BASE_URL 环境变量,以 BASE_URL 为准(它优先级更高)。
  envs: {
    test: 'http://localhost:3000', // 测试环境地址
    uat: 'http://uat.example.com', // 预发/验收环境地址(改成你们真实的)
    prod: 'http://example.com' // 生产环境地址(改成你们真实的)
  },

  // ── 内置功能开关 ────────────────────────────────────────────────
  switches: {
    // 选择器缓存:干嘛用的?
    //   测试跑过一遍之后,tester 会记住"页面上这个按钮用哪个选择器能找到"，
    //   存到 test-result/locator-cache.json。下次再跑同样用例,直接拿记忆里的
    //   选择器去用,不用每次重新猜——又快又稳,还能省 AI 的 token 开销。
    //   什么情况要关:页面结构天天变、每跑一次定位就失败一次的时候,
    //   可以暂时关掉排查是不是缓存"记住了旧位置"。
    //   等价环境变量:TESTER_LOCATOR_CACHE=0 关闭 / =1 打开
    locatorCache: true,

    // 跨用例变量:干嘛用的?
    //   自动化测试最常见的长链路是"创建→查询→编辑→删除",后面的用例要用
    //   前面用例造出来的数据(比如新建订单后拿到订单号,查询用例拿它去查)。
    //   这个开关允许用例之间互相传数据(用 setVar/getVar),关掉就只能单条
    //   用例自己玩,做不了长链路。
    //   等价环境变量:TESTER_VARS=0 关闭 / =1 打开
    vars: true
  },

  // ── 失败自动重试 ─────────────────────────────────────────────────
  // 干嘛用的:跑测试偶尔会"误报"——不是系统真有 bug,而是网络抖了一下、
  //   页面加载慢了一拍、按钮还没出现就点了,这类叫"偶发失败/Flaky"。
  //   这里设置:遇到这类失败自动重跑几轮,重跑过了就算通过。
  //   注意:只有"定位/网络/超时"这类环境抖动才重试;真·断言失败
  //   (系统真错了)不重试——重试也没用,还浪费时间。
  // 怎么改:maxRounds 改大 = 更容忍偶发失败但更慢;改小 = 更快但更容易误报。
  retry: {
    maxRounds: 2, // 最多自动重试 2 轮(0 就是不重试)
    retryable: ['定位', '网络', '超时'] // 只有这几类失败才重试
  },

  // ── VLM 视觉兜底(进阶功能,默认关) ─────────────────────────────
  // 干嘛用的:正常定位靠"页面结构"(文本、按钮名、id),快又准。但有些页面
  //   太特殊——纯 Canvas 画布、自己封装的封闭组件——结构定位怎么都找不到。
  //   这个开关允许在这种时候,把页面截图发给一个"能看图的 AI 模型"(视觉模型),
  //   让它告诉你目标在哪,再用坐标去点。
  // 开启需要 3 件事:
  //   1) 下面 enabled 改成 true
  //   2) 填好 model / apiUrl / apiKey(见下面每行的说明)
  //   3) plugin/ 目录放一个视觉插件(模板自带 vlm.example.cjs,复制改名 vlm.cjs)
  //   三者齐了,tester 才会真正去调模型。
  // 注意:apiKey 是敏感信息,建议别写死在这里——优先设环境变量 TESTER_VLM_API_KEY,
  //   环境变量的优先级更高,也不会把密钥提交进代码仓库。
  vlm: {
    enabled: false, // true = 允许视觉兜底
    model: 'glm-4v', // 你用的视觉模型名字(按你接入的服务填,如 glm-4v / qwen-vl-max / gpt-4o)
    apiUrl: 'https://你的模型服务地址/v1/chat/completions', // 视觉模型服务的 API 地址(换成真实的)
    apiKey: '' // 你的 API key(推荐不填这里,改用环境变量 TESTER_VLM_API_KEY)
  }
};
